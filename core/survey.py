MIN_SCORE, MAX_SCORE = 7, 35

TYPES = {
    "안정추구형": {"range": (7, 10), "desc": "약간의 리스크만 허용하고, 물가수준 이상의 수익을 추구하는 투자자"},
    "위험중립형": {"range": (11, 24), "desc": "적당한 리스크를 허용하여 장기적으로 완만한 수익을 추구하는 투자자"},
    "공격추구형": {"range": (25, 35), "desc": "금융시장의 큰 변동성을 감수하면서 고수익을 기대하는 투자자"},
}


def option_score(option_index: int) -> int:
    """보기 번호(0 = ①) -> 점수 (① 5점 ... ⑤ 1점)."""
    return 5 - option_index


def total_score(answers: list[int]) -> int:
    return sum(option_score(a) for a in answers)


def classify(score: int) -> str:
    if score <= 10:
        return "안정추구형"
    if score <= 24:
        return "위험중립형"
    return "공격추구형"


def score_to_position(score: float) -> float:
    """점수 -> 프론티어 위 상대 위치(0 = MVP, 1 = 최고 수익률). 점수에 비례."""
    return (score - MIN_SCORE) / (MAX_SCORE - MIN_SCORE)


def type_band(type_name: str) -> tuple[float, float]:
    """성향 구간의 프론티어 상대 위치 범위. 경계는 10.5점, 24.5점."""
    lo, hi = TYPES[type_name]["range"]
    lo = MIN_SCORE if lo == MIN_SCORE else lo - 0.5
    hi = MAX_SCORE if hi == MAX_SCORE else hi + 0.5
    return score_to_position(lo), score_to_position(hi)
